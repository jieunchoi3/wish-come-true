function writeModule(name, exportName, items) {
  const body = `const BASE = ${JSON.stringify(items[0]?.default_tags ?? {}, null, 2)}

export const ${exportName} = ${JSON.stringify(items, null, 2).replace(/"default_tags": \{[^}]+\}/g, (m, offset, str) => {
    // keep default_tags as spread reference - actually stringify fully is fine
    return m
  })}
`
  // Fix default_tags to use spread - simpler to just inline full objects
  writeFileSync(join(dir, `${name}.js`), body)
}


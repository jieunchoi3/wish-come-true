function dedupe(raw, keyFn) {
  const seen = new Set()
  const out = []
  for (const row of raw) {
    const k = keyFn(row)
    if (seen.has(k)) continue
    seen.add(k)
    out.push(row)
  }
  return out
}

function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

